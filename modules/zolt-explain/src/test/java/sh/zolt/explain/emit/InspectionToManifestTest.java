    @Test
    void mavenDraftEmitsDependencyExclusions() throws IOException {
        Files.writeString(tempDir.resolve("pom.xml"), """
                <project>
                  <modelVersion>4.0.0</modelVersion>
                  <groupId>com.example</groupId>
                  <artifactId>demo</artifactId>
                  <version>1.0.0</version>
                  <dependencies>
                    <dependency>
                      <groupId>com.google.guava</groupId>
                      <artifactId>guava</artifactId>
                      <version>33.2.1-jre</version>
                      <exclusions>
                        <exclusion>
                          <groupId>com.google.code.findbugs</groupId>
                          <artifactId>jsr305</artifactId>
                        </exclusion>
                        <exclusion>
                          <groupId>org.checkerframework</groupId>
                          <artifactId>checker-qual</artifactId>
                        </exclusion>
                      </exclusions>
                    </dependency>
                  </dependencies>
                </project>
                """);

        DraftZoltToml draft = mapper.fromMaven(new MavenStaticProjectInspector().inspect(tempDir));
        DraftManifestSubject subject = DraftManifestSubject.of(draft);

        // An exclusion is one exact `group:artifact` coordinate now, not a (group, artifact) pair.
        List<String> exclusions = subject
                .dependency(DependencyLane.IMPLEMENTATION, "com.google.guava:guava")
                .metadata()
                .exclusions()
                .stream()
                .map(DependencyCoordinate::value)
                .toList();
        assertEquals(2, exclusions.size(), () -> "guava exclusions should be recorded: " + exclusions);
        assertTrue(exclusions.contains("com.google.code.findbugs:jsr305"),
                () -> "missing the findbugs exclusion: " + exclusions);
        assertTrue(exclusions.contains("org.checkerframework:checker-qual"),
                () -> "missing the checkerframework exclusion: " + exclusions);
    }

