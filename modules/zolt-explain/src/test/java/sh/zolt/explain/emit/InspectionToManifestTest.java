    @Test
    void mavenChildInheritingParentManagementEmitsConcreteVersions() throws IOException {
        Files.writeString(tempDir.resolve("pom.xml"), """
                <project>
                  <modelVersion>4.0.0</modelVersion>
                  <groupId>com.example</groupId>
                  <artifactId>root</artifactId>
                  <version>2.0.0</version>
                  <packaging>pom</packaging>
                  <modules>
                    <module>service</module>
                  </modules>
                  <properties>
                    <maven.compiler.release>17</maven.compiler.release>
                    <jackson.version>2.17.1</jackson.version>
                  </properties>
                  <dependencyManagement>
                    <dependencies>
                      <dependency>
                        <groupId>com.fasterxml.jackson.core</groupId>
                        <artifactId>jackson-databind</artifactId>
                        <version>${jackson.version}</version>
                      </dependency>
                      <dependency>
                        <groupId>org.junit.jupiter</groupId>
                        <artifactId>junit-jupiter</artifactId>
                        <version>5.11.4</version>
                        <scope>test</scope>
                      </dependency>
                    </dependencies>
                  </dependencyManagement>
                </project>
                """);
        Path service = tempDir.resolve("service");
        Files.createDirectories(service);
        Files.writeString(service.resolve("pom.xml"), """
                <project>
                  <modelVersion>4.0.0</modelVersion>
                  <parent>
                    <groupId>com.example</groupId>
                    <artifactId>root</artifactId>
                    <version>2.0.0</version>
                  </parent>
                  <artifactId>service</artifactId>
                  <dependencies>
                    <dependency>
                      <groupId>com.fasterxml.jackson.core</groupId>
                      <artifactId>jackson-databind</artifactId>
                    </dependency>
                    <dependency>
                      <groupId>org.junit.jupiter</groupId>
                      <artifactId>junit-jupiter</artifactId>
                      <scope>test</scope>
                    </dependency>
                  </dependencies>
                </project>
                """);

        MavenInspectionResult reactor = new MavenStaticProjectInspector().inspect(tempDir);
        // Emit the child module on its own (mirrors per-module emit): the mapper reads projects.get(0).
        MavenProjectInspection child = reactor.projects().stream()
                .filter(project -> project.artifactId().equals("service"))
                .findFirst()
                .orElseThrow();
        DraftZoltToml draft = mapper.fromMaven(
                new MavenInspectionResult(service, List.of(child), List.of()));
        DraftManifestSubject subject = DraftManifestSubject.of(draft);

        assertEquals(Optional.of(17), subject.javaRelease(), "child inherits the parent java version");
        assertEquals(Optional.of("2.0.0"), subject.version());
        assertEquals(Optional.of("com.example"), subject.group());
        assertEquals("2.17.1",
                subject.fixed(DependencyLane.IMPLEMENTATION).get("com.fasterxml.jackson.core:jackson-databind"),
                () -> "the implementation lane must carry the inherited concrete version: "
                        + subject.fixed(DependencyLane.IMPLEMENTATION));
        assertEquals("5.11.4", subject.fixed(DependencyLane.TEST).get("org.junit.jupiter:junit-jupiter"),
                () -> "the test lane must carry the inherited concrete version: "
                        + subject.fixed(DependencyLane.TEST));
        assertFalse(subject.coordinates(DependencyLane.IMPLEMENTATION).isEmpty(),
                "the implementation lane must not be empty");
        assertFalse(subject.coordinates(DependencyLane.TEST).isEmpty(), "the test lane must not be empty");
        assertFalse(
                draft.notes().stream().anyMatch(note -> note.contains("no static version")),
                () -> "no false version-less review comments for parent-managed deps: " + draft.notes());
    }

