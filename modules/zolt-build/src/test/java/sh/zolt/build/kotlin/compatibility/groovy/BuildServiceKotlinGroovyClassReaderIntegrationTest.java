package sh.zolt.build.kotlin.compatibility.groovy;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import groovy.lang.GroovyObject;
import java.io.IOException;
import java.io.InputStream;
import java.net.URL;
import java.net.URLClassLoader;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.nio.file.StandardOpenOption;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.ArrayList;
import java.util.HexFormat;
import java.util.List;
import java.util.jar.JarEntry;
import java.util.jar.JarOutputStream;
import java.util.stream.Stream;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import sh.zolt.build.BuildResult;
import sh.zolt.build.BuildResultWithClasspaths;
import sh.zolt.build.BuildService;
import sh.zolt.build.KotlinCompilerIntegrationArtifacts;
import sh.zolt.project.ProjectConfig;
import sh.zolt.toml.manifest.adapter.ManifestProjectConfigLoader;

/** Real-toolchain proof for Kotlin's legacy reader against Groovy-generated bytecode. */
final class BuildServiceKotlinGroovyClassReaderIntegrationTest {
    private static final String GROOVY_VERSION = "4.0.22";
    private static final String PROVIDER_VERSION = "1.0.0";

    @TempDir
    private Path tempDir;

    @Test
    void readsGroovyDependencyAndInvalidatesReaderChanges() throws Exception {
        Path cacheRoot = tempDir.resolve("cache");
        Path provider = tempDir.resolve("provider");
        CachedArtifact groovy = cacheGroovyRuntime(cacheRoot);
        writeGroovyProvider(provider);
        writeGroovyLock(provider.resolve("zolt.lock"), groovy);

        BuildResult providerBuild = new BuildService().build(
                provider,
                groovyConfig(),
                cacheRoot,
                true);
        assertFalse(providerBuild.mainCompilationSkipped());
        assertTrue(Files.isRegularFile(
                provider.resolve("target/classes/com/example/provider/GroovyGreeting.class")));

        Path providerJar = jarClasses(
                provider.resolve("target/classes"),
                tempDir.resolve("groovy-provider-" + PROVIDER_VERSION + ".jar"));
        Path consumer = tempDir.resolve("consumer");
        KotlinCompilerIntegrationArtifacts.prepare(
                cacheRoot,
                consumer.resolve("zolt.lock"));
        cacheConsumerDependency(cacheRoot, consumer.resolve("zolt.lock"), providerJar, groovy);
        writeKotlinConsumer(consumer);
        BuildService service = new BuildService();

        BuildResultWithClasspaths modern = build(service, consumer, cacheRoot, false);
        assertFalse(modern.buildResult().mainCompilationSkipped());
        assertEquals("groovy-kotlin", invoke(consumer, modern));

        BuildResultWithClasspaths modernWarm = build(service, consumer, cacheRoot, false);
        assertTrue(modernWarm.buildResult().mainCompilationSkipped());

        BuildResultWithClasspaths legacy = build(service, consumer, cacheRoot, true);
        assertFalse(legacy.buildResult().mainCompilationSkipped());
        assertEquals("groovy-kotlin", invoke(consumer, legacy));

        BuildResultWithClasspaths legacyWarm = build(service, consumer, cacheRoot, true);
        assertTrue(legacyWarm.buildResult().mainCompilationSkipped());

        BuildResultWithClasspaths restored = build(service, consumer, cacheRoot, false);
        assertFalse(restored.buildResult().mainCompilationSkipped());
        assertEquals("groovy-kotlin", invoke(consumer, restored));
    }

    private static BuildResultWithClasspaths build(
            BuildService service,
            Path project,
            Path cacheRoot,
            boolean legacyReader) {
        return service.buildWithClasspaths(
                project,
                kotlinConfig(legacyReader),
                cacheRoot,
                true);
    }

    private static Object invoke(
            Path project,
            BuildResultWithClasspaths result) throws Exception {
        List<URL> urls = new ArrayList<>();
        urls.add(project.resolve("target/classes").toUri().toURL());
        for (Path dependency : result.classpaths().runtime().entries()) {
            urls.add(dependency.toUri().toURL());
        }
        try (URLClassLoader loader = new URLClassLoader(
                urls.toArray(URL[]::new),
                ClassLoader.getPlatformClassLoader())) {
            return Class.forName("com.example.consumer.KotlinConsumer", true, loader)
                    .getMethod("message")
                    .invoke(null);
        }
    }

    private static void writeGroovyProvider(Path project) throws IOException {
        Path source = project.resolve(
                "src/main/groovy/com/example/provider/GroovyGreeting.groovy");
        Files.createDirectories(source.getParent());
        Files.writeString(source, """
                package com.example.provider

                final class GroovyGreeting {
                    static String message(String name) {
                        "groovy-${name}"
                    }
                }
                """);
    }

    private static void writeKotlinConsumer(Path project) throws IOException {
        Path source = project.resolve(
                "src/main/kotlin/com/example/consumer/KotlinConsumer.kt");
        Files.createDirectories(source.getParent());
        Files.writeString(source, """
                package com.example.consumer

                import com.example.provider.GroovyGreeting

                object KotlinConsumer {
                    @JvmStatic
                    fun message(): String = GroovyGreeting.message("kotlin")
                }
                """);
    }

    private static CachedArtifact cacheGroovyRuntime(Path cacheRoot) throws Exception {
        Path source = Path.of(GroovyObject.class
                .getProtectionDomain()
                .getCodeSource()
                .getLocation()
                .toURI());
        return cacheArtifact(cacheRoot, source, "groovy-" + GROOVY_VERSION + ".jar");
    }

    private static void cacheConsumerDependency(
            Path cacheRoot,
            Path lockfile,
            Path providerJar,
            CachedArtifact groovy) throws IOException {
        CachedArtifact provider = cacheArtifact(
                cacheRoot,
                providerJar,
                "groovy-provider-" + PROVIDER_VERSION + ".jar");
        Files.writeString(lockfile, """

                [[dependencyRoot]]
                member = "."
                id = "com.example:groovy-provider"
                version = "%s"
                lane = "implementation"
                resolvedScope = "compile"

                [[package]]
                id = "com.example:groovy-provider"
                version = "%s"
                source = "fixture"
                scope = "compile"
                direct = true
                jar = "%s"
                jarSha256 = "%s"
                dependencies = ["org.apache.groovy:groovy:%s:jar:compile"]

                [[package]]
                id = "org.apache.groovy:groovy"
                version = "%s"
                source = "fixture"
                scope = "compile"
                direct = false
                jar = "%s"
                jarSha256 = "%s"
                dependencies = []
                """.formatted(
                PROVIDER_VERSION,
                PROVIDER_VERSION,
                provider.relativePath(),
                provider.sha256(),
                GROOVY_VERSION,
                GROOVY_VERSION,
                groovy.relativePath(),
                groovy.sha256()), StandardOpenOption.APPEND);
    }

    private static CachedArtifact cacheArtifact(
            Path cacheRoot,
            Path source,
            String fileName) throws IOException {
        String digest = sha256(source);
        Path relative = Path.of("blobs", "v2", "sha256", digest, fileName);
        Path target = cacheRoot.resolve(relative);
        Files.createDirectories(target.getParent());
        Files.copy(source, target, StandardCopyOption.REPLACE_EXISTING);
        return new CachedArtifact(
                relative.toString().replace('\\', '/'),
                digest);
    }

    private static void writeGroovyLock(
            Path lockfile,
            CachedArtifact groovy) throws IOException {
        Files.writeString(lockfile, """
                version = 7

                [[dependencyRoot]]
                member = "."
                id = "org.apache.groovy:groovy"
                version = "%s"
                lane = "implementation"
                resolvedScope = "compile"

                [[package]]
                id = "org.apache.groovy:groovy"
                version = "%s"
                source = "fixture"
                scope = "compile"
                direct = true
                jar = "%s"
                jarSha256 = "%s"
                dependencies = []

                [[package]]
                id = "org.apache.groovy:groovy"
                version = "%s"
                source = "fixture"
                scope = "tool-groovy"
                direct = true
                jar = "%s"
                jarSha256 = "%s"
                dependencies = []
                """.formatted(
                GROOVY_VERSION,
                GROOVY_VERSION,
                groovy.relativePath(),
                groovy.sha256(),
                GROOVY_VERSION,
                groovy.relativePath(),
                groovy.sha256()));
    }

    private static Path jarClasses(Path classes, Path jar) throws IOException {
        try (JarOutputStream output = new JarOutputStream(Files.newOutputStream(jar));
                Stream<Path> paths = Files.walk(classes)) {
            for (Path path : paths.filter(Files::isRegularFile)
                    .filter(value -> value.getFileName().toString().endsWith(".class"))
                    .sorted()
                    .toList()) {
                JarEntry entry = new JarEntry(
                        classes.relativize(path).toString().replace('\\', '/'));
                entry.setTime(0L);
                output.putNextEntry(entry);
                Files.copy(path, output);
                output.closeEntry();
            }
        }
        return jar;
    }

    private static String sha256(Path path) throws IOException {
        try {
            MessageDigest digest = MessageDigest.getInstance("SHA-256");
            try (InputStream input = Files.newInputStream(path)) {
                byte[] buffer = new byte[8192];
                for (int read = input.read(buffer); read >= 0; read = input.read(buffer)) {
                    digest.update(buffer, 0, read);
                }
            }
            return HexFormat.of().formatHex(digest.digest());
        } catch (NoSuchAlgorithmException exception) {
            throw new AssertionError("SHA-256 is unavailable", exception);
        }
    }

    private static ProjectConfig groovyConfig() {
        return new ManifestProjectConfigLoader().load("""
                [project]
                name = "groovy-provider"
                version = "%s"
                group = "com.example"
                java = %s

                [build]
                sources = ["src/main/groovy"]

                [toolchain.groovy]
                version = "%s"

                [dependencies]
                "org.apache.groovy:groovy" = "%s"
                """.formatted(
                PROVIDER_VERSION,
                Runtime.version().feature(),
                GROOVY_VERSION,
                GROOVY_VERSION));
    }

    private static ProjectConfig kotlinConfig(boolean legacyReader) {
        String compilerSettings = legacyReader
                ? """
                        [compiler]
                        args = ["-Xuse-old-class-files-reading"]
                        """
                : "";
        return new ManifestProjectConfigLoader().load("""
                [project]
                name = "kotlin-groovy-consumer"
                version = "0.1.0"
                group = "com.example"
                java = %s

                [build]
                sources = ["src/main/kotlin"]

                [toolchain.kotlin]
                version = "2.2.0"

                %s

                [dependencies]
                "org.jetbrains.kotlin:kotlin-stdlib" = "2.2.0"
                "com.example:groovy-provider" = "%s"
                """.formatted(
                Runtime.version().feature(),
                compilerSettings,
                PROVIDER_VERSION));
    }

    private record CachedArtifact(String relativePath, String sha256) {
    }
}
